#!/usr/bin/env python3
"""Generate/check the primary-key enumerator shared by the three SQL dialects."""
import argparse
from pathlib import Path

TEMPLATE = '''// Code generated by generate_execution_enumeration.py. DO NOT EDIT.

package {package}

import (
    "context"

    "go.temporal.io/server/common/persistence/sql/sqlplugin"
)

func (mdb *db) SelectExecutionKeys(ctx context.Context, page sqlplugin.ExecutionKeyPage) ([]sqlplugin.ExecutionsRow, error) {{
    query := `SELECT shard_id, namespace_id, workflow_id, run_id FROM executions WHERE shard_id = {p1}`
    args := []any{{page.ShardID}}
    if page.After != nil {{
        query += ` AND (namespace_id, workflow_id, run_id) > ({p2}, {p3}, {p4})`
        args = append(args, page.After.NamespaceID, page.After.WorkflowID, page.After.RunID)
    }}
    query += ` ORDER BY namespace_id, workflow_id, run_id LIMIT `
    if page.After == nil {{ query += "{p2}" }} else {{ query += "{p5}" }}
    args = append(args, page.Limit)
    var rows []sqlplugin.ExecutionsRow
    err := mdb{conn}.SelectContext(ctx, &rows, query, args...)
    return rows, err
}}

var _ sqlplugin.ExecutionKeyReader = (*db)(nil)
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).parent
    for dialect in ("mysql", "postgresql", "sqlite"):
        params = {f"p{i}": f"${i}" if dialect == "postgresql" else "?" for i in range(1, 6)}
        data = TEMPLATE.format(package=dialect, conn=".conn" if dialect == "sqlite" else "", **params)
        path = root / dialect / "execution_enumeration.go"
        # gofmt is the authoritative formatter for generated code.
        import subprocess
        data = subprocess.run(["gofmt"], input=data, text=True, capture_output=True, check=True).stdout
        if args.check:
            if not path.exists() or path.read_text() != data:
                raise SystemExit(f"stale generated file: {path}")
        else:
            path.write_text(data)

if __name__ == "__main__":
    main()
